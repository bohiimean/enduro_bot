"""Ловушка для сообщений, не подошедших ни одному хендлеру.

Подключается последним роутером. Без неё бот на неожиданное сообщение молчит:
именно так пропало фото прописки, присланное после того, как кнопка меню
сбросила шаг сценария. Молчание в ответ на фото паспорта — худший из возможных
ответов: человек уверен, что документ отправлен, а его нет нигде.

Клавиатуру здесь намеренно не трогаем: пользователь может ждать верификацию, и
подмена меню на main_keyboard унесла бы кнопки «Статус верификации» и
«Отправить документы заново».
"""
from aiogram import Router
from aiogram.types import Message

from handlers.start import BTN_KYC_STATUS

router = Router()


@router.message()
async def unhandled(message: Message) -> None:
    if message.photo or message.document:
        await message.answer(
            "На этом шаге я не жду файлов, поэтому <b>никуда его не отправил</b>.\n\n"
            f"Если это документ для верификации — нажмите «{BTN_KYC_STATUS}» в меню: "
            "бот скажет, чего не хватает.",
            parse_mode="HTML",
        )
        return

    await message.answer("Не понял. Выберите действие в меню ниже.")
